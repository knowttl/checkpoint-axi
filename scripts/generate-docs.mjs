import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { catalogue, DESCRIPTION, SETUP_GUIDANCE } from "../dist/src/catalogue.js";

const root = new URL("../", import.meta.url);
const check = process.argv.includes("--check");
const generated = "<!-- Generated by scripts/generate-docs.mjs from src/catalogue.ts. Do not hand-edit. -->";
const escape = (value) => value.replaceAll("|", "\\|").replaceAll("\n", " ");
const commands = Object.entries(catalogue).sort(([a], [b]) => a.localeCompare(b, "en"));
const invocation = (example) => example.replace(/^checkpoint-axi(?= |$)/, "npx -y @knowttl/checkpoint-axi");
const table = (prefix) => ["| Command | Purpose |", "|---|---|", ...commands.map(([name, entry]) =>
  `| \`${prefix} ${name}\` | ${escape(entry.description)} |`)].join("\n");
const reference = `${generated}\n\n# Command reference\n\n${DESCRIPTION}.\nC1 commands are local and never contact Check Point.\nRun each command with \`--help\` for concise help.\n\n${commands.map(([name, entry]) => [
  `## ${name}`, "", entry.description, "", "| Flag | Meaning |", "|---|---|",
  ...Object.entries(entry.flags).map(([flag, meaning]) => `| \`--${flag}\` | ${escape(meaning)} |`), "",
  "```sh", ...entry.examples, "```", "",
].join("\n")).join("\n")}\n`;
const skill = `---\nname: checkpoint-axi\ndescription: "Inspect Check Point Email Security CLI configuration, list profiles and validate local credential readiness with compact TOON output."\n---\n\n${generated}\n\n# checkpoint-axi\n\n${DESCRIPTION}.\nC1 ships local discovery only; API operations and Artium integration arrive in later slices.\nUse \`npx -y @knowttl/checkpoint-axi\` after publication without a global install.\nBare \`--version\`, \`-v\` and \`-V\` print the package version.\n\n${SETUP_GUIDANCE.replaceAll("checkpoint-axi", "npx -y @knowttl/checkpoint-axi")}.\nSecrets use environment/file SecretRefs, never inline values, argv or chat.\nRegions are us, eu, ca, au, uk, uae and in; arbitrary origins are refused.\n\n\`\`\`sh\n${catalogue.home.examples.map(invocation).join("\n")}\n${invocation(catalogue["auth status"].examples[0])}\n\`\`\`\n\nHome and the optional checkpoint-axi-hook binary read local context only.\nConfigure a session hook only on explicit request; C1 never installs one automatically.\nUse the hook for ambient discovery or this skill for on-demand discovery.\nLocal auth status validates secret availability and file security without authenticating to the API.\nDo not infer API access from a local pass.\nUse --full for strings truncated at 500 characters and --fields for output projection.\n\n${table("npx -y @knowttl/checkpoint-axi")}\n`;
const readmePath = new URL("README.md", root);
const readme = readFileSync(readmePath, "utf8");
const start = "<!-- command-registry:start -->\n", end = "\n<!-- command-registry:end -->";
if (readme.split(start).length !== 2 || readme.split(end).length !== 2) throw new Error("README command registry markers missing or duplicated");
const summary = `${readme.split(start)[0]}${start}${table("checkpoint-axi")}${end}${readme.split(end)[1]}`;
const outputs = new Map([["docs/commands.md", `${reference.trimEnd()}\n`], ["skills/checkpoint-axi/SKILL.md", skill], ["README.md", summary]]);
let stale = false;
for (const [path, content] of outputs) {
  const url = new URL(path, root);
  if (check) {
    let current;
    try { current = readFileSync(url, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
    if (current !== content) { console.error(`Stale generated documentation: ${path}; build and run docs:generate`); stale = true; }
  } else {
    mkdirSync(dirname(fileURLToPath(url)), { recursive: true });
    writeFileSync(url, content);
  }
}
if (stale) process.exitCode = 1;
